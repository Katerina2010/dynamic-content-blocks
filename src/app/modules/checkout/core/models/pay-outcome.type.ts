/**
 * Результат команды `pay()`:
 * - `ignored`: повторная отправка или отправка в неподходящем состоянии;
 * - `ineligible`: покупка была недопустима ещё до списания;
 * - `conflict`: списание одобрено, но за это время покупка стала недопустимой
 *   (например, её оформили в другой вкладке), поэтому она не сохранена и успех не показан.
 */
export type PayOutcome = 'ignored' | 'ineligible' | 'conflict' | 'approved' | 'declined' | 'error';
