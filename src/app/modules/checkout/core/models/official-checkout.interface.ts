/** Проверенная официальная страница оплаты The Bell для одного тарифа. */
export interface OfficialCheckout {
  /** Точный URL в проверенном виде, без параметров отслеживания. */
  readonly url: string;
  /** Цена так, как она напечатана на этой странице оплаты при проверке, например "$14,90/месяц". */
  readonly priceOnCheckout: string;
  /**
   * Существенные условия, напечатанные на этой странице оплаты; показываются читателю до перехода
   * (например, что не входит в пробный тариф, пока он не продлится в платный).
   */
  readonly termsOnCheckout?: string;
}
