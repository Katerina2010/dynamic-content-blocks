/**
 * - `upcoming`: начало ещё не наступило.
 * - `started`: начало прошло, но по Москве всё ещё тот же календарный день. Настоящая
 *   длительность не опубликована, поэтому блок никогда не утверждает, что эфир ещё идёт
 *   или что он закончился; он лишь сообщает, что эфир начался, и не продаёт доступ к нему.
 * - `past`: со следующего календарного дня. Полночь — граница отображения (дата события
 *   прошла), а не вычисленное время окончания эфира.
 */
export type WebinarStatus = 'upcoming' | 'started' | 'past';
