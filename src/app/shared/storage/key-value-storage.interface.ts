import { Observable } from 'rxjs';

/**
 * Минимальное постоянное хранилище «ключ — значение».
 * Реализации никогда не выбрасывают исключений.
 */
export interface KeyValueStorage {
  /** Возвращает сохранённую строку или `null`, если значения нет или хранилище недоступно. */
  read(key: string): string | null;
  /** Возвращает `true`, только если значение действительно сохранено. */
  write(key: string, value: string): boolean;
  /**
   * Сообщает, когда `key` изменён другим контекстом просмотра того же origin (другой вкладкой),
   * включая полную очистку. Об изменениях, сделанных через этот экземпляр, не сообщается.
   */
  externalChanges(key: string): Observable<void>;
}
